def glyph(platform, *, size=20, colour="#0b1f33", muted=False):
    """An inline <svg> for one platform, or an em dash when it has no glyph."""
    path = PLATFORM_PATHS.get(platform)
    if not path:
        return mark_safe("&mdash;")
    return format_html(
        '<svg viewBox="0 0 24 24" width="{}" height="{}" fill="{}" '
        'style="vertical-align:middle;opacity:{}" aria-hidden="true">'
        '<path fill-rule="evenodd" clip-rule="evenodd" d="{}"/></svg>',
        size,
        size,
        colour,
        "0.3" if muted else "1",
        path,
    )
